"""startswith() method"""
str = "Python"
print(str.startswith('a'))
print(str.startswith('p'))

"""endswith() method"""
print(str.endswith('n'))
print(str.endswith('a'))


"""isalpha() method"""
print(str.isalpha())


"""isdigit() method"""
print(str.isdigit())


"""isalnum() method"""
print(str.isalnum())